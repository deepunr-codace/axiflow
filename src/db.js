import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { AsyncLocalStorage } from 'node:async_hooks';

/*
 * Postgres data layer.
 *  - Production (Vercel): Supabase Postgres (or any Postgres) via DATABASE_URL, using node-postgres with a
 *    small pool. On Vercel use Supabase's Transaction pooler URL (port 6543): the direct db.<ref> host is IPv6-only.
 *  - Local without DATABASE_URL: embedded Postgres (PGlite) stored in DATA_DIR/pg.
 * All functions are async. SQL uses :name parameters (converted to $1, $2…); objects are stored as JSON
 * text, booleans as 0/1 (the schema keeps SQLite-era INTEGER flags and TEXT ISO timestamps).
 * Modules add their own tables with registerSchema()/addColumns(); the schema is applied once per
 * process, and skipped entirely when its hash matches the one stored in the database.
 */
const DATABASE_URL = process.env.DATABASE_URL || process.env.POSTGRES_URL || '';
export const DATA_DIR = process.env.DATA_DIR || path.resolve('data');
export const usingRemote = !!DATABASE_URL;

let driver = null; // { query(text, params) -> {rows, rowCount}, tx(fn) }
const txStore = new AsyncLocalStorage();

const INT8 = 20, NUMERIC = 1700;
function normalise(rows, fields) {
  const ints = (fields || []).filter((f) => f.dataTypeID === INT8 || f.dataTypeID === NUMERIC).map((f) => f.name);
  for (const r of rows) {
    for (const k of Object.keys(r)) {
      const v = r[k];
      if (typeof v === 'bigint') r[k] = Number(v);
      else if (typeof v === 'string' && ints.includes(k)) r[k] = Number(v);
    }
  }
  return rows;
}

async function makeDriver() {
  if (usingRemote) {
    const { default: pg } = await import('pg');
    pg.types.setTypeParser(INT8, (v) => (v === null ? null : Number(v)));
    pg.types.setTypeParser(NUMERIC, (v) => (v === null ? null : Number(v)));
    // Supabase/managed Postgres need TLS; their CA is not in Node's store, so verify the host but not the chain.
    const url = new URL(DATABASE_URL);
    const local = ['localhost', '127.0.0.1'].includes(url.hostname);
    url.searchParams.delete('sslmode');
    const pool = new pg.Pool({
      connectionString: url.toString(),
      ssl: local ? false : { rejectUnauthorized: false },
      max: process.env.VERCEL ? 3 : 10,
      idleTimeoutMillis: 10000,
      connectionTimeoutMillis: 10000,
    });
    pool.on('error', (e) => console.error('[db] idle client error', e.message));
    if (process.env.VERCEL) {
      try { const { attachDatabasePool } = await import('@vercel/functions'); attachDatabasePool(pool); } catch { /* older runtime */ }
    }
    const wrap = (c) => ({ async query(text, params) { const r = await c.query(text, params); return { rows: r.rows, rowCount: r.rowCount ?? r.rows.length }; } });
    return {
      ...wrap(pool),
      async tx(fn) {
        const client = await pool.connect();
        try {
          await client.query('BEGIN');
          const out = await txStore.run(wrap(client), fn);
          await client.query('COMMIT');
          return out;
        } catch (e) {
          await client.query('ROLLBACK').catch(() => {});
          throw e;
        } finally {
          client.release();
        }
      },
      close: () => pool.end(),
    };
  }
  if (process.env.VERCEL) throw new Error('DATABASE_URL is not set. Add your Supabase Transaction pooler connection string in Vercel > Project > Settings > Environment Variables, then redeploy.');
  const { PGlite } = await import('@electric-sql/pglite');
  const dir = path.join(DATA_DIR, 'pg');
  fs.mkdirSync(dir, { recursive: true });
  const pg = new PGlite(dir);
  await pg.waitReady;
  const wrap = (c) => ({ async query(text, params) { const r = await c.query(text, params); return { rows: normalise(r.rows, r.fields), rowCount: r.affectedRows ?? r.rows.length }; } });
  return {
    ...wrap(pg),
    tx: (fn) => pg.transaction((t) => txStore.run(wrap(t), fn)),
    close: () => pg.close(),
  };
}

// ------------------------------------------------------------- schema
const schema = []; // ordered: DDL blocks (SQLite-flavoured, translated below) and column additions
export function registerSchema(sql) { schema.push({ sql }); }
export function addColumns(table, cols) { schema.push({ table, cols }); }

const pgDDL = (s) => s
  .replace(/INTEGER PRIMARY KEY AUTOINCREMENT/g, 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
  .replace(/\bREAL\b/g, 'DOUBLE PRECISION');
const statements = (s) => s.split('\n').filter((l) => !l.trim().startsWith('--')).join('\n').split(';').map((x) => x.trim()).filter(Boolean);

let readyPromise = null;
/** Opens the database and applies the schema (once per process). Every query waits for it. */
export function ready() {
  if (!readyPromise) readyPromise = (async () => {
    driver = await makeDriver();
    const ddl = schema.flatMap((b) => (b.sql ? statements(pgDDL(b.sql))
      : Object.entries(b.cols).map(([c, type]) => `ALTER TABLE ${b.table} ADD COLUMN IF NOT EXISTS ${c} ${pgDDL(type)}`)));
    const hash = crypto.createHash('sha1').update(ddl.join(';')).digest('hex');
    try {
      const r = await driver.query(`SELECT value FROM settings WHERE key = 'schema_hash'`);
      if (r.rows[0]?.value === hash) return;
    } catch { /* first run: settings table does not exist yet */ }
    for (const st of ddl) await driver.query(st);
    await driver.query(`INSERT INTO settings (key, value) VALUES ('schema_hash', $1) ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value`, [hash]);
  })().catch((e) => { readyPromise = null; throw e; });
  return readyPromise;
}

// ------------------------------------------------------------- queries
function cleanValue(v) {
  if (v === undefined) return null;
  if (typeof v === 'boolean') return v ? 1 : 0;
  if (v !== null && typeof v === 'object') return JSON.stringify(v);
  return v;
}

/** ":name" → "$n" (skipping quoted strings and "::" casts); "?" works for array params. */
function compile(sql, params) {
  if (Array.isArray(params)) {
    let i = 0;
    return { text: sql.replace(/\?/g, () => `$${++i}`), values: params.map(cleanValue) };
  }
  const values = [];
  const index = new Map();
  let out = '';
  for (let i = 0; i < sql.length; i++) {
    const ch = sql[i];
    if (ch === "'") { const j = sql.indexOf("'", i + 1); out += sql.slice(i, j + 1); i = j; continue; }
    if (ch === ':' && sql[i + 1] === ':') { out += '::'; i++; continue; }
    if (ch === ':' && /[A-Za-z_]/.test(sql[i + 1] || '')) {
      let j = i + 1;
      while (j < sql.length && /\w/.test(sql[j])) j++;
      const name = sql.slice(i + 1, j);
      if (!index.has(name)) { values.push(cleanValue(params?.[name])); index.set(name, values.length); }
      out += '$' + index.get(name);
      i = j - 1;
      continue;
    }
    out += ch;
  }
  return { text: out, values };
}

async function query(sql, params = {}) {
  await ready();
  const { text, values } = compile(sql, params);
  const c = txStore.getStore() || driver;
  try {
    return await c.query(text, values);
  } catch (e) {
    e.message = `${e.message} [SQL: ${text.replace(/\s+/g, ' ').slice(0, 300)}]`;
    throw e;
  }
}

export async function get(sql, params = {}) { return (await query(sql, params)).rows[0] || null; }
export async function all(sql, params = {}) { return (await query(sql, params)).rows; }
export async function run(sql, params = {}) { const r = await query(sql, params); return { changes: r.rowCount, rows: r.rows }; }

const columnCache = new Map();
async function columns(table) {
  if (!columnCache.has(table)) {
    const rows = await all(`SELECT column_name FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = :table`, { table });
    columnCache.set(table, new Set(rows.map((c) => c.column_name)));
  }
  return columnCache.get(table);
}

export async function insert(table, data) {
  const cols = await columns(table);
  const keys = Object.keys(data).filter((k) => cols.has(k) && k !== 'id');
  const sql = `INSERT INTO ${table} (${keys.join(',')}) VALUES (${keys.map((k) => ':' + k).join(',')})${cols.has('id') ? ' RETURNING id' : ''}`;
  const r = await query(sql, Object.fromEntries(keys.map((k) => [k, data[k]])));
  return r.rows[0] ? Number(r.rows[0].id) : null;
}

export async function update(table, id, data) {
  const cols = await columns(table);
  const keys = Object.keys(data).filter((k) => cols.has(k) && k !== 'id');
  if (!keys.length) return 0;
  const params = Object.fromEntries(keys.map((k) => [k, data[k]]));
  params.id = id;
  return (await query(`UPDATE ${table} SET ${keys.map((k) => `${k} = :${k}`).join(', ')} WHERE id = :id`, params)).rowCount;
}

/** Runs fn inside one transaction; get/all/run/insert/update inside it use the same connection. */
export async function transaction(fn) {
  await ready();
  if (txStore.getStore()) return fn();
  return driver.tx(fn);
}

/** Closes the local embedded database (scripts). */
export async function close() { if (driver?.close) await driver.close(); }

