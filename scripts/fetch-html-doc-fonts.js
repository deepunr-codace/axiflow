// Downloads the brochure template's web fonts (the exact Google Fonts CSS request the reference HTML made) into
// assets/html-docs/fonts and writes brochure-fonts.css pointing at them. Run once: node scripts/fetch-html-doc-fonts.js
// Only the latin, latin-ext and malayalam pieces are kept (the HTML documents are English with Malayalam display words).
import fs from 'node:fs';
import path from 'node:path';
const DIR = path.resolve('assets/html-docs/fonts');
const URL = 'https://fonts.googleapis.com/css2?family=Fraunces:ital,opsz,wght@0,9..144,300;0,9..144,400;0,9..144,500;0,9..144,600;1,9..144,400;1,9..144,500&family=Instrument+Sans:wght@400;500;600&family=Noto+Serif+Malayalam:wght@600;800&display=block';
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/138.0.0.0 Safari/537.36';
const css = await (await fetch(URL, { headers: { 'user-agent': UA } })).text();
const blocks = css.split(/(?=\/\* )/).filter((b) => /\/\* (latin|latin-ext|malayalam) \*\//.test(b));
const seen = new Map();
let out = '/* Generated by scripts/fetch-html-doc-fonts.js from Google Fonts (OFL). */\n';
for (const b of blocks) {
  const url = b.match(/url\((https:[^)]+\.woff2)\)/)?.[1];
  if (!url) continue;
  if (!seen.has(url)) {
    const fam = b.match(/font-family: '([^']+)'/)[1].toLowerCase().replace(/\s+/g, '-');
    const sub = b.match(/\/\* ([\w-]+) \*\//)[1];
    const name = `${fam}-${sub}-${seen.size}.woff2`;
    fs.writeFileSync(path.join(DIR, name), Buffer.from(await (await fetch(url)).arrayBuffer()));
    seen.set(url, name);
  }
  out += b.replace(url, `{{font:${seen.get(url)}}}`);
}
fs.writeFileSync(path.join(DIR, 'brochure-fonts.css'), out);
console.log(`${seen.size} font files, ${blocks.length} @font-face rules`);
